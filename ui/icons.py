def data_uri(name: str) -> str:
    """The icon as an inline SVG, quoted for a CSS `url(...)`."""
    width, path = FA[name]
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" '
           f'viewBox="0 0 {width} 512"><path d="{path}"/></svg>')
    return "url(\"data:image/svg+xml," + quote(svg, safe="") + "\")"
